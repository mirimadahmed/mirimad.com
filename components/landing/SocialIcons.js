const PLATFORM_FROM_TITLE = {
  github: "github",
  linkedin: "linkedin",
  youtube: "youtube",
  instagram: "instagram",
  tiktok: "tiktok",
  email: "email",
  phone: "phone",
};

const SocialIcons = ({ socials, className = "", iconClassName = "", location = "footer" }) => {
  const items = socials
    .map((s) => ({ ...s, key: PLATFORM_FROM_TITLE[s.title.toLowerCase()] }))
    .filter((s) => s.key && ICONS[s.key]);

  return (
    <ul className={`flex flex-wrap items-center gap-3 ${className}`}>
      {items.map((s) => {
        const isExternal = s.link.startsWith("http");
        return (
          <li key={s.id || s.key}>
            <a
              href={s.link}
              {...(isExternal ? { target: "_blank", rel: "noopener noreferrer" } : {})}
              onClick={() => track("social_clicked", { platform: s.key, location })}
              aria-label={s.title}
              title={s.title}
              className={`flex h-9 w-9 items-center justify-center rounded-full border lp-border transition-colors hover:bg-black/5 dark:hover:bg-white/10 ${iconClassName}`}
            >
              {ICONS[s.key]}
            </a>
          </li>
        );
      })}
    </ul>
  );
};

export default SocialIcons;
